const field = (
  apiName: string,
  dataType: string,
  options: Partial<Omit<DataField, 'apiName' | 'dataType' | 'provenance'>> = {},
): DataField => ({
  apiName,
  label: options.label ?? apiName,
  dataType,
  description: options.description ?? null,
  isPrimaryKey: options.isPrimaryKey ?? false,
  isNullable: options.isNullable ?? !options.isPrimaryKey,
  provenance: provenance('/ssot/fields'),
});

